#!/usr/bin/env node
// Writes server/harness/omp/companion-hash.ts from harness-extension/omp.ts. Paseo bundles plugin server
// code as CommonJS, where import.meta.url is empty, so the server can't locate the companion file at runtime.
import { createHash } from "node:crypto";
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const source = fs.readFileSync(fileURLToPath(new URL("../harness-extension/omp.ts", import.meta.url)));
const hash = createHash("sha256").update(source).digest("hex");
const target = fileURLToPath(new URL("../server/harness/omp/companion-hash.ts", import.meta.url));
fs.writeFileSync(target, `// Generated by scripts/sync-companion-hash.mjs from harness-extension/omp.ts; do not edit.\nexport const COMPANION_SHA256 = "${hash}";\n`);
console.log(`companion sha256 ${hash}`);
